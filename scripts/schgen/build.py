#!/usr/bin/env python3
"""Build the KiCad 10 schematic from scripts/schgen/design/*.py into hardware/e-inverted-pendulum/ (D-020, D-033).

The sheets follow the e-psu-hardware pattern: titled boxes per functional block, wired circuits, design notes, and a
root page that describes every sheet. `expected.json` records the intended connectivity for `check.py`.

Usage: python3 scripts/schgen/build.py
"""

import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "design"))

from sch import Project  # noqa: E402
import drive, imu_flash, logic_power, mcu, motors_encoders, power_entry, rf, ui  # noqa: E402,E401

OUT = HERE.parents[1] / "hardware" / "e-inverted-pendulum"
EXPECTED = HERE / "expected.json"
NAME = "e-inverted-pendulum"
TITLE = "e-inverted-pendulum: self-balancing robot chassis PCB"
GENERATED = "Generated by scripts/schgen/build.py (D-020): do not edit by hand"
MODULES = (power_entry, logic_power, mcu, rf, drive, motors_encoders, imu_flash, ui)

ROOT_NOTES = [
    ("e-inverted-pendulum  rev A", 30.48, 30.48, 2.54, True),
    ("Two-wheeled self-balancing robot. The PCB is the chassis: STM32WB55 (BLE), DRV8711 driving two MG310 gear\n"
     "motors through external half-bridges, MPU-6500 IMU, 3S LiPo. Firmware: github.com/embedded-pro/e-inverted-pendulum",
     30.48, 38.1, 1.5, False),
    ("Power flow:  3S LiPo (9.0-12.6 V) -> XT30 J101 -> 4 A fuse F101 -> back-to-back P-FET switch Q101 (reverse polarity,\n"
     "soft start, SW101) -> VBAT -> SMBJ15A clamp -> DRV8711 + four CSD88537ND half-bridges -> MG310 motors\n"
     "VBAT -> TPS62933F buck -> +5V (encoders, buzzer, LDO) -> TLV75533P LDO -> +3V3 (MCU, IMU, flash, I2C devices)\n"
     "MCU core: +3V3 -> internal SMPS (L301 + L302) -> VFBSMPS;  VDDA through ferrite FB301",
     30.48, 190.5, 1.5, False),
    ("Ground: one GND, L2 solid and never cut. The motor current returns through Rsense R509 / R512 at the bridges;\n"
     "the Kelvin taps NT501 / NT502 keep the sense lines off the power ground.  Numbering: sheet n uses references n01-n99.\n"
     "Sources for every value: docs/design-calcs.md, docs/decisions.md, simulation/REPORT.md.",
     30.48, 213.36, 1.5, False),
]


def main():
    values = json.loads((HERE / "values.json").read_text(encoding="utf-8"))
    project = Project(NAME, TITLE, date="2026-11-13", rev="A", company="embedded-pro", comments=[GENERATED])
    for module in MODULES:
        module.build(project, values)
    problems = project.problems()
    for problem in problems:
        print("PROBLEM", problem)
    if problems:
        sys.exit(1)
    project.build(OUT, ROOT_NOTES)
    EXPECTED.write_text(project.expected_json(), encoding="utf-8")
    for path in sorted(OUT.glob("*.kicad_sch")):
        subprocess.run(["kicad-cli", "sch", "upgrade", "--force", str(path)], check=True, capture_output=True)
    for line in project.lint:
        print("LINT", line)
    count = len({p.ref for s in project.sheets for p in s.parts if not p.ref.startswith("#")})
    print(f"wrote {len(project.sheets)} sheets, {count} parts to {OUT}; layout lint {len(project.lint)}")
    sys.exit(1 if project.lint else 0)


if __name__ == "__main__":
    main()
